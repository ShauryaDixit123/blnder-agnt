class Plan(TypedDict):
    id: str =  Field(name="id", description="The unique identifier for the plan step")
    agent_id: str = Field(name="id", description="The agent id identifier for the plan step")
    operation: str = Field(..., description="The operation to be performed in this step")
    args: dict = Field(default_factory=dict)
    depends_on: list[str] = Field(default_factory=list, description="List of step IDs that this step depends on")
    to_be_completed_in_this: str = Field(name="to_be_completed_in_this", description="This will be completed in this step according to plan.")
    comleted_in_this_step: Optional[str] = Field(name="comleted_in_this_step", description="What is completed in this step")

class AgentState(TypedDict):
    messages: Annotated[list[BaseMessage], add_messages]
    plan: Optional[list[Plan]] = Field(None, description="The plan generated by the planner node")
    current_plan_step: int = Field(None, description="Current step in the workflow")
    completed_steps: Optional[list[str]] = Field(None, description="The list of completed steps in the plan")
    failed_steps: Optional[list[str]] = Field(None, description="The list of failed steps in the plan")
    blender_tools = any

